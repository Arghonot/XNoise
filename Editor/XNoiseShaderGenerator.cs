using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using CustomGraph;
using UnityEditor;
using UnityEngine;
using XNode;

namespace XNoise
{
    public static class XNoiseShaderGenerator
    {
        private const string OutputFolder = "Assets/XNoise/Shaders/Generated";

        [MenuItem("Assets/XNoise/Generate Single-Pass Shader")]
        private static void GenerateFromSelection()
        {
            if (Selection.activeObject is not XnoiseGraph graph)
            {
                Debug.LogError("[XNoise] Select an XnoiseGraph asset first.");
                return;
            }
            GenerateAndSave(graph);
        }

        [MenuItem("Assets/XNoise/Generate Single-Pass Shader", true)]
        private static bool GenerateFromSelectionValidate() => Selection.activeObject is XnoiseGraph;

        // Saves the generated shader and returns its Shader.Find() name.
        public static string GenerateAndSave(XnoiseGraph graph)
        {
            var shaderText = Generate(graph);

            if (!AssetDatabase.IsValidFolder(OutputFolder))
                AssetDatabase.CreateFolder("Assets/XNoise/Shaders", "Generated");

            var sanitized = graph.name.Replace(" ", "_");
            var assetPath = $"{OutputFolder}/{sanitized}.shader";
            File.WriteAllText(Path.GetFullPath(assetPath), shaderText);
            AssetDatabase.ImportAsset(assetPath);

            var shaderName = $"Xnoise/Generated/{graph.name}";
            Debug.Log($"[XNoise] Shader saved to {assetPath}  —  use Shader.Find(\"{shaderName}\")");
            return shaderName;
        }

        // Builds the shader text by traversing the XNode graph directly.
        public static string Generate(XnoiseGraph graph)
        {
            // 1. Find the XNoiseNode wired into the root's Input port.
            var rootInputPort = graph.rootNode.GetInputPort("Input");
            if (rootInputPort == null || !rootInputPort.IsConnected)
                throw new System.InvalidOperationException($"[XNoise] Graph '{graph.name}': root node has no connected input.");

            var topNode = rootInputPort.Connection.node;

            // 2. Collect all emitter nodes in post-order (children before parents).
            var ordered = new List<Node>();
            var visited = new HashSet<Node>();
            CollectPostOrder(topNode, visited, ordered);

            // 3. Assign unique HLSL function names.
            var fnNames = new Dictionary<Node, string>();
            for (int i = 0; i < ordered.Count; i++)
                fnNames[ordered[i]] = $"xn_{i}";

            // 4. Collect unique uniforms and includes, preserving first-seen order.
            var uniformsSeen = new HashSet<string>();
            var uniforms = new List<ShaderUniform>();
            var includesSeen = new HashSet<string>();
            var includes = new List<string>();

            foreach (var node in ordered)
            {
                if (node is not IShaderEmitter emitter) continue;
                foreach (var u in emitter.Uniforms)
                    if (uniformsSeen.Add(u.Name)) uniforms.Add(u);
                foreach (var inc in emitter.RequiredIncludes)
                    if (includesSeen.Add(inc)) includes.Add(inc);
            }

            // 5. Emit each node's HLSL function.
            var functions = new StringBuilder();
            foreach (var node in ordered)
            {
                if (node is not IShaderEmitter emitter) continue;
                functions.AppendLine(emitter.EmitFunction(fnNames[node], fnNames));
                functions.AppendLine();
            }

            return BuildShader(graph.name, includes, uniforms, functions.ToString(), fnNames[topNode]);
        }

        // Traverses the XNode graph in post-order.
        // BlackBoardVariable nodes are skipped — they become uniforms, not functions.
        private static void CollectPostOrder(Node node, HashSet<Node> visited, List<Node> ordered)
        {
            if (!visited.Add(node)) return;
            if (node is BlackBoardVariable) return;

            foreach (var port in node.Ports)
            {
                if (!port.IsInput || !port.IsConnected) continue;
                var child = port.Connection.node;
                if (child is BlackBoardVariable) continue;
                CollectPostOrder(child, visited, ordered);
            }

            if (node is IShaderEmitter)
                ordered.Add(node);
        }

        private static string BuildShader(
            string graphName,
            List<string> includes,
            List<ShaderUniform> uniforms,
            string nodeFunctions,
            string rootFn)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// Auto-generated by XNoiseShaderGenerator — do not edit manually.");
            sb.AppendLine($"Shader \"Xnoise/Generated/{graphName}\"");
            sb.AppendLine("{");

            if (uniforms.Count > 0)
            {
                sb.AppendLine("    Properties");
                sb.AppendLine("    {");
                foreach (var u in uniforms)
                    sb.AppendLine($"        {u.Name}(\"{u.Name.TrimStart('_')}\", Float) = {u.Default.ToString("F2", CultureInfo.InvariantCulture)}");
                sb.AppendLine("    }");
            }

            sb.AppendLine("    SubShader");
            sb.AppendLine("    {");
            sb.AppendLine("        Cull Off ZWrite Off ZTest Always");
            sb.AppendLine("        Tags { \"RenderType\"=\"Opaque\" }");
            sb.AppendLine();
            sb.AppendLine("        CGINCLUDE");
            sb.AppendLine("        #include \"UnityCG.cginc\"");
            foreach (var inc in includes)
                sb.AppendLine($"        #include \"../CGINCs/{inc}\"");
            sb.AppendLine();

            foreach (var u in uniforms)
                sb.AppendLine($"        float {u.Name};");
            if (uniforms.Count > 0) sb.AppendLine();

            sb.AppendLine("        struct appdata { float4 vertex : POSITION; float2 uv : TEXCOORD0; };");
            sb.AppendLine("        struct v2f { float4 vertex : SV_POSITION; float2 uv : TEXCOORD0; };");
            sb.AppendLine();
            sb.AppendLine("        v2f vert(appdata v)");
            sb.AppendLine("        {");
            sb.AppendLine("            v2f o;");
            sb.AppendLine("            o.vertex = UnityObjectToClipPos(v.vertex);");
            sb.AppendLine("            o.uv = v.uv;");
            sb.AppendLine("            return o;");
            sb.AppendLine("        }");
            sb.AppendLine();

            foreach (var line in nodeFunctions.Split('\n'))
                sb.AppendLine("        " + line.TrimEnd());

            sb.AppendLine("        ENDCG");
            sb.AppendLine();

            AppendPass(sb, "PLANAR",      rootFn, "GetPlanarCartesianFromUV(i.uv, float3(0.0, 0.0, 0.0))");
            AppendPass(sb, "SPHERICAL",   rootFn, "GetSphericalCartesianFromUV(i.uv, 1.0)");
            AppendPass(sb, "CYLINDRICAL", rootFn, "GetCylindricalCartesianFromUV(i.uv, float3(0.0, 0.0, 0.0), 1.0)");

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void AppendPass(StringBuilder sb, string name, string rootFn, string coordExpr)
        {
            var fragName = $"frag_{name.ToLower()}";
            sb.AppendLine("        Pass");
            sb.AppendLine("        {");
            sb.AppendLine($"            Name \"{name}\"");
            sb.AppendLine("            CGPROGRAM");
            sb.AppendLine("            #pragma vertex vert");
            sb.AppendLine($"            #pragma fragment {fragName}");
            sb.AppendLine();
            sb.AppendLine($"            float {fragName}(v2f i) : SV_Target");
            sb.AppendLine("            {");
            sb.AppendLine($"                float3 coord = {coordExpr};");
            sb.AppendLine($"                return {rootFn}(coord);");
            sb.AppendLine("            }");
            sb.AppendLine("            ENDCG");
            sb.AppendLine("        }");
            sb.AppendLine();
        }
    }
}
